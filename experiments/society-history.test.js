"use strict";
const assert=require("node:assert/strict");
const {makeSociety,acceptSocietyEvent,projectSociety}=require("./society-history.js");
const citizen=id=>({id,skill:{farm:0},interest:{farm:0.9},needs:{food:1},traits:{openness:0.5,riskTolerance:0.5},beliefs:{commons:0},history:[]});
const original=makeSociety("world-1",[citizen("a"),citizen("b")]);
const receipt=(id,citizenId,kind,tick,extra={})=>({eventId:id,worldId:"world-1",citizenId,kind,tick,verified:true,...extra});
let s=original;
const work=receipt("w1","a","work_success",1,{jobId:"gather",domain:"farm"});
s=acceptSocietyEvent(s,work);assert.equal(projectSociety(s).citizens[0].history.length,1);
assert.equal(acceptSocietyEvent(s,work),s);
assert.throws(()=>acceptSocietyEvent(s,{...work,jobId:"other"}),/conflicting replay/);
assert.throws(()=>acceptSocietyEvent(s,{...work,eventId:"other",worldId:"world-2"}),/invalid/);
assert.throws(()=>acceptSocietyEvent(s,{...work,eventId:"other",verified:false}),/unverified/);
assert.throws(()=>acceptSocietyEvent(s,{...work,eventId:"other",tick:0}),/out of order/);
s=acceptSocietyEvent(s,receipt("w2","a","work_success",2,{jobId:"gather",domain:"farm"}));
s=acceptSocietyEvent(s,receipt("w3","a","work_success",3,{jobId:"gather",domain:"farm"}));
assert.equal(projectSociety(s).occupations.a[0].domain,"farm");
assert.equal(projectSociety(original).occupations.a.length,0);
const c1=receipt("c1","a","cooperation",4,{transactionId:"tx1",partnerId:"b",domain:"farm"});
s=acceptSocietyEvent(s,c1);
assert.equal(projectSociety(s).cooperations.length,0);
assert.throws(()=>acceptSocietyEvent(s,receipt("forged","a","cooperation",5,{transactionId:"tx1",partnerId:"b",domain:"farm"})),/conflicting joint/);
s=acceptSocietyEvent(s,receipt("c2","b","cooperation",5,{transactionId:"tx1",partnerId:"a",domain:"farm"}));
assert.equal(projectSociety(s).cooperations.length,1);
assert.equal(projectSociety(s).organizations.length,0);
s=acceptSocietyEvent(s,receipt("c3","a","cooperation",6,{transactionId:"tx2",partnerId:"b",domain:"farm"}));
s=acceptSocietyEvent(s,receipt("c4","b","cooperation",7,{transactionId:"tx2",partnerId:"a",domain:"farm"}));
assert.equal(projectSociety(s).organizations.length,1);
assert.equal(projectSociety(s,{nowTick:30000,cooperationWindow:100}).organizations.length,0);
assert.throws(()=>acceptSocietyEvent(s,receipt("bad","a","civic_signal",8,{topic:"commons",value:Infinity,reliability:1})),/invalid civic/);
s=acceptSocietyEvent(s,receipt("p1","a","civic_signal",8,{topic:"commons",value:1,reliability:1}));
assert.ok(projectSociety(s).citizens[0].beliefs.commons>0);
const restored=JSON.parse(JSON.stringify(s));
assert.deepEqual(projectSociety(restored),projectSociety(s));
assert.equal(projectSociety(s,{nowTick:2}).occupations.a.length,0);
const capped=makeSociety("world-1",[citizen("a")],1);
assert.throws(()=>acceptSocietyEvent(acceptSocietyEvent(capped,work),receipt("w2","a","work_success",2,{jobId:"gather",domain:"farm"})),/capacity/);
console.log("society history: 20 assertions passed");
